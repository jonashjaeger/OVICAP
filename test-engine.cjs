assert.ok(scenario.sheep.mean>950 && scenario.sheep.mean<1100,scenario.sheep.mean);
const r=E.rng(35);let total=0;for(let i=0;i<10000;i++)total+=E.binomial(3000,.15,r);near(total/10000,450,3);
const parsed=E.parseCSV('name,notes,ambiguous\r\n"A, B","line1\nline2",120\r\n');assert.deepEqual(parsed,[{name:'A, B',notes:'line1\nline2',ambiguous:'120'}]);
const out=E.toCSV(E.scenarioRows([x]));assert.equal(E.parseCSV(out)[0].zooSheep,'33');
