const assert=require('node:assert/strict');
const E=require('../engine.js');
const near=(x,y,e=.002)=>assert.ok(Math.abs(x-y)<e,`${x} not near ${y}`);
// Core paper's detection example at goat share 2%.
near(E.detectionBinomial(.02,34),1-.98**34,1e-10);
near(E.detectionBinomial(.02,33),1-.98**33,1e-10);
assert.equal(E.detectionBinomial(0,33),0);
assert.equal(E.detectionBinomial(1,33),1);
assert.equal(E.detectionFinite(10,1,1),.1);
assert.equal(E.detectionFinite(10,2,9),1);
near(E.detectionFinite(10,2,2),1-(8*7)/(10*9),1e-10);
assert.equal(E.sampleTarget(.02,1,.95),149);
near(E.zeroSuccessUpper(33),1-.05**(1/33),1e-10);
const x=E.DEMO;
assert.equal(E.validate(x).errors.length,0);
assert.equal(E.validate({...x,zooFail:1500}).errors.length,1);
assert.ok(E.validate({...x,morphGoat:3.25}).errors.length>0);
const a=E.estimate(x),b=E.estimate(x);
assert.deepEqual(a.goat,b.goat,'reproducible');
assert.equal(a.tested,45);assert.equal(a.diagnostic,34);assert.equal(a.unresolved,1403);
near(a.sheep.mean+a.goat.mean+a.other.mean,a.observedTotal,1e-8);
assert.equal(a.distributions.sheep.length,6000);
for(let i=0;i<500;i++)assert.equal(a.distributions.sheep[i]+a.distributions.goat[i]+a.distributions.other[i],a.observedTotal);
const scenario=E.estimate({name:'Hypothesis',morphSheep:80,morphGoat:10,ambiguous:1200,zooSheep:80,zooGoat:20,zooOther:0,zooFail:0,strategy:'random',threeTaxa:false,prior:0.5});
